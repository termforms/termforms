"""Generates runtime/src/tui/tf_width_tables.c: how many terminal cells
each character takes, from the Unicode Character Database as Python's
unicodedata module carries it (so nothing is downloaded).

    python3 tools/gen_width_tables.py      # rewrites the file

Run it when moving to a newer Python whose Unicode version is newer, and
commit the result; the file says which Unicode version it came from.

Widths, as terminals draw them (and as glibc's wcwidth, in the main):
  2  East_Asian_Width W (wide) or F (fullwidth); since Unicode 9 this
     includes the emoji drawn as emoji by default.
  0  combining marks (Mn, Me), format characters (Cf, but not the soft
     hyphen or the marks that are drawn: the prepended concatenation
     marks), Hangul medial vowels and final consonants (U+1160-U+11FF,
     drawn as part of the syllable before them), and controls.
  1  everything else, East_Asian_Width A (ambiguous) included: terminals
     draw those narrow outside a CJK locale.
"""

import pathlib
import sys
import unicodedata

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "runtime/src/tui/tf_width_tables.c"

# Format characters that are drawn (UAX #44 Prepended_Concatenation_Mark,
# which unicodedata does not carry, and the soft hyphen).
DRAWN_FORMAT = {0x00AD, 0x0600, 0x0601, 0x0602, 0x0603, 0x0604, 0x0605, 0x06DD,
                0x070F, 0x0890, 0x0891, 0x08E2, 0x110BD, 0x110CD}

# Ideograph blocks whose unassigned code points are wide by default.
WIDE_BY_DEFAULT = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
                   (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]


def width(cp):
    if cp < 0x20 or 0x7F <= cp < 0xA0:
        return 0
    if 0x1160 <= cp <= 0x11FF:
        return 0
    c = chr(cp)
    category = unicodedata.category(c)
    if category in ("Mn", "Me") or (category == "Cf" and cp not in DRAWN_FORMAT):
        return 0
    if unicodedata.east_asian_width(c) in ("W", "F"):
        return 2
    if category == "Cn" and any(lo <= cp <= hi for lo, hi in WIDE_BY_DEFAULT):
        return 2
    return 1


def ranges(want):
    """The code point ranges whose width is want, merged."""
    found = []
    start = None
    for cp in range(0x110000 + 1):
        inside = cp <= 0x10FFFF and width(cp) == want
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            found.append((start, cp - 1))
            start = None
    return found


def table(name, rows):
    lines = [f"const tf_width_range {name}[] = {{"]
    for lo, hi in rows:
        lines.append(f"    {{0x{lo:05X}, 0x{hi:05X}}},")
    lines.append("};")
    lines.append(f"const int {name}_count = {len(rows)};")
    return "\n".join(lines)


def main():
    text = f"""/* SPDX-License-Identifier: 0BSD AND Unicode-3.0 */
/*
 * tf_width_tables.c -- GENERATED by tools/gen_width_tables.py from the
 * Unicode Character Database {unicodedata.unidata_version} (Python's unicodedata). Do not edit.
 *
 * The data is Unicode's: see runtime/THIRD_PARTY_NOTICES. Ranges are
 * sorted and do not overlap; tf_width.c searches them.
 */
#include "tf_width.h"

/* One range a line, as generated. */
/* clang-format off */
{table("tf_zero_width", ranges(0))}

{table("tf_wide", ranges(2))}
/* clang-format on */
"""
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} (Unicode {unicodedata.unidata_version})", file=sys.stderr)


if __name__ == "__main__":
    main()
